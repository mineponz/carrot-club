/** 父名から系統を引く。表に無い父・父不明はすべて「その他」。 */
export function sireLineOf(sire: string | null | undefined): SireLine {
  if (!sire) return 'その他';
  return SIRE_LINE_TABLE[sire] ?? 'その他';
}

